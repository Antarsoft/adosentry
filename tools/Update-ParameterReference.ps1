#Requires -Version 7.0
<#
.SYNOPSIS
    Generates docs/parameters.md from the parameters of ai-code-review/stage-template.yml.

.DESCRIPTION
    Reads the template's `parameters:` block: each parameter's name, type, default and allowed
    values, and the comment lines directly above its `- name:` line as its description. Writes a
    Markdown table to docs/parameters.md.

    With -Check, writes nothing and fails if docs/parameters.md is not what the template would
    generate. CI runs it that way, so the reference cannot drift from the template.

.EXAMPLE
    pwsh tools/Update-ParameterReference.ps1

.EXAMPLE
    pwsh tools/Update-ParameterReference.ps1 -Check
#>
[CmdletBinding()]
param(
    [string]$TemplatePath = (Join-Path $PSScriptRoot '..' 'ai-code-review' 'stage-template.yml'),
    [string]$OutputPath = (Join-Path $PSScriptRoot '..' 'docs' 'parameters.md'),
    [switch]$Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Get-StageTemplateParameter {
    param([string[]]$Lines)

    $parameters = [System.Collections.Generic.List[object]]::new()
    $comments = [System.Collections.Generic.List[string]]::new()
    $current = $null
    $inValues = $false
    $inBlock = $false

    foreach ($line in $Lines) {
        if (-not $inBlock) {
            if ($line -match '^parameters:\s*$') { $inBlock = $true }
            continue
        }
        # The block ends at the next top-level key (stages:).
        if ($line -match '^\S') { break }

        if ($line -match '^\s*#\s?(.*)$') {
            $comments.Add($Matches[1].Trim())
            $inValues = $false
            continue
        }
        if ($line -match '^\s*-\s+name:\s*(\S+)\s*$') {
            $current = [ordered]@{
                Name        = $Matches[1]
                Type        = ''
                Default     = $null
                Values      = [System.Collections.Generic.List[string]]::new()
                Description = ($comments -join ' ').Trim()
            }
            $parameters.Add($current)
            $comments.Clear()
            $inValues = $false
            continue
        }
        if ($null -eq $current) { continue }

        if ($line -match '^\s+type:\s*(\S+)\s*$') {
            $current.Type = $Matches[1]; $inValues = $false
        }
        elseif ($line -match '^\s+default:\s*(.*?)\s*$') {
            $current.Default = ConvertFrom-YamlScalar $Matches[1]; $inValues = $false
        }
        elseif ($line -match '^\s+values:\s*$') {
            $inValues = $true
        }
        elseif ($inValues -and $line -match '^\s+-\s+(.+?)\s*$') {
            $current.Values.Add((ConvertFrom-YamlScalar $Matches[1]))
        }
    }

    if ($parameters.Count -eq 0) {
        throw "No parameters found in the template's parameters: block."
    }
    return $parameters
}

function ConvertFrom-YamlScalar {
    param([string]$Text)

    if ($Text -match '^"(.*)"$' -or $Text -match "^'(.*)'$") { return $Matches[1] }
    return $Text
}

function Format-Cell {
    param([string]$Text)

    return ($Text -replace '\|', '\|')
}

function Format-ParameterReference {
    param($Parameters)

    $out = [System.Collections.Generic.List[string]]::new()
    $out.Add('# Stage parameters')
    $out.Add('')
    $out.Add('<!-- Generated by tools/Update-ParameterReference.ps1 from ai-code-review/stage-template.yml. Do not edit by hand: change the comments in the template and run the script. CI fails if this file is out of date. -->')
    $out.Add('')
    $out.Add('Parameters of [`ai-code-review/stage-template.yml`](../ai-code-review/stage-template.yml), the PullPicket review stage. Pass them under `parameters:` where your pipeline uses the template. Model settings (`modelName`, `modelDeploymentUrl`, `reasoningEffort`) come from the variable group named in `modelVariableGroup`, not from parameters; see the [quick start](../README.md#4-create-the-variable-group).')
    $out.Add('')
    $out.Add('| Parameter | Type | Default | Description |')
    $out.Add('| --- | --- | --- | --- |')

    foreach ($p in $Parameters) {
        $default = if ($null -eq $p.Default) { '(required)' }
                   elseif ($p.Default -eq '') { '(empty)' }
                   else { "``$($p.Default)``" }
        $description = $p.Description
        if ($p.Values.Count -gt 0) {
            $allowed = ($p.Values | ForEach-Object { "``$_``" }) -join ', '
            $description = "$description Allowed values: $allowed.".Trim()
        }
        $out.Add("| ``$($p.Name)`` | $($p.Type) | $default | $(Format-Cell $description) |")
    }

    return ($out -join "`n") + "`n"
}

$templateLines = Get-Content -LiteralPath $TemplatePath
$expected = Format-ParameterReference (Get-StageTemplateParameter $templateLines)

if ($Check) {
    $actual = if (Test-Path -LiteralPath $OutputPath) { (Get-Content -LiteralPath $OutputPath -Raw) -replace "`r`n", "`n" } else { '' }
    if ($actual -ne $expected) {
        throw "docs/parameters.md is out of date with ai-code-review/stage-template.yml. Run: pwsh tools/Update-ParameterReference.ps1"
    }
    Write-Host 'docs/parameters.md is up to date.'
    return
}

[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($OutputPath), $expected, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $OutputPath"
